const TYPE_ORDER = ['事実確認', '気持ち', '想像', '比較', '未来'];

function ageBand(age) {
  const n = parseInt(age, 10);
  if (!n || isNaN(n)) return 'lower';
  if (n <= 6) return 'toddler';
  if (n <= 9) return 'lower';
  if (n <= 12) return 'upper';
  return 'teen';
}

function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

// 教科指定がある場合、その教科で重視するタイプを先頭に寄せる（順序の軽い調整のみ）
const SUBJECT_PRIORITY = {
  国語: '気持ち',
  算数: '事実確認',
  理科: '想像',
  社会: '比較',
  道徳: '気持ち',
};

export function getFallbackQuestions(options = {}) {
  const band = ageBand(options.age);
  const bank = FALLBACK_BANK[band] || FALLBACK_BANK.lower;

  const questions = TYPE_ORDER.map((type) => ({
    type,
    text: pick(bank[type]),
  }));

  // 教科指定があれば、その重視タイプを先頭へ
  const priorityType = options.subject && SUBJECT_PRIORITY[options.subject];
  if (priorityType) {
    const idx = questions.findIndex((q) => q.type === priorityType);
    if (idx > 0) {
      const [item] = questions.splice(idx, 1);
      questions.unshift(item);
    }
  }

  return questions;
}
